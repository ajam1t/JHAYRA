// Plain-language answers built from the live size and finish tables.
export function categoryFaq(name, { sizes = [], colours = [] } = {}) {
  const list = sizes.map((s) => `${s.name} (${s.dimensions}) ₹${Math.round(+s.base_price || +s.price || 0).toLocaleString('en-IN')}`).join(', ');
  const fin = colours.map((c) => c.name.toLowerCase()).join(', ');
  return [
    [`What sizes does ${name.toLowerCase()} come in?`, list ? `Every design is available in ${sizes.length} sizes: ${list}.` : 'Every design is available in four sizes, from A4 to 24 × 36 inches.'],
    ['Which frame finishes can I choose?', fin ? `Each piece comes in a ${fin} frame — you choose on the product page.` : 'Each piece comes in a black, gold or brown frame.'],
    ['How long does delivery take?', 'Every piece is made to order: 1–2 business days to craft and quality-check, then 5–7 business days in transit. Delivery is free to every pincode we serve in India.'],
    ['What if it arrives damaged?', 'Send us photos or a short video on WhatsApp within 48 hours of delivery and we will replace it at no extra cost.'],
  ];
}

